# ---------------------------------------------------------
# Configuration
# ---------------------------------------------------------

# Resolve paths relative to this file, regardless of
# the directory from which the application is started.
BASE_DIR = Path(__file__).resolve().parent
PROJECT_DIR = BASE_DIR.parent

REPORT_PATH = BASE_DIR / "reports" / "latest-report.json"
SCREENSHOT_DIR = BASE_DIR / "screenshots"

HISTORY_DIR = SCREENSHOT_DIR / "history"

# Load the API key from the project's root .env file.
load_dotenv(PROJECT_DIR / ".env")

API_KEY = os.getenv("DESIGNCHECK_API_KEY")

# Read authentication credentials from the X-API-Key header.
api_key_header = APIKeyHeader(
    name="X-API-Key",
    auto_error=False,
)

# Configure application logging.
logger = logging.getLogger(__name__)

# Store active scan jobs in memory.
# Completed jobs are also persisted in SQLite.
scan_jobs = {}

# Protect shared job data from concurrent modifications.
jobs_lock = threading.Lock()

# Prevent multiple screenshot scans from running simultaneously.
scan_lock = threading.Lock()


# ---------------------------------------------------------
# Application Lifecycle
# ---------------------------------------------------------

@asynccontextmanager
async def lifespan(app: FastAPI):
    """
    Initialize application resources during startup.

    Ensures that:
    - An API key has been configured.
    - The SQLite database exists.
    - Interrupted scans are marked as failed.

    Args:
        app (FastAPI): The application instance.
    """

    # Refuse to start without API authentication.
    if not API_KEY:
        raise RuntimeError(
            "DESIGNCHECK_API_KEY is not configured."
        )

    # Create database tables when necessary.
    initialize_database()

    # Recover records left pending or running
    # after an unexpected service shutdown.
    recover_interrupted_scans()

    logger.info("WP DesignChecker initialized successfully.")

    yield

    logger.info("WP DesignChecker shutting down.")


# Create the FastAPI application.
app = FastAPI(
    title="WP DesignChecker API",
    description="Visual regression testing engine for WordPress.",
    version="0.1.0",
    lifespan=lifespan,
)


# ---------------------------------------------------------
# Authentication
# ---------------------------------------------------------

def authenticate(
    api_key: str | None = Depends(api_key_header)
):
    """
    Authenticate requests using the configured API key.

    Args:
        api_key (str | None): Key supplied in X-API-Key.

    Raises:
        HTTPException: When authentication fails.
    """

    # Compare credentials without ordinary string equality.
    if (
        not API_KEY
        or not api_key
        or not secrets.compare_digest(api_key, API_KEY)
    ):
        raise HTTPException(
            status_code=401,
            detail="Unauthorized",
        )


def archive_scan_screenshots(scan_id: str):
    """
    Preserve screenshots generated by an individual scan.

    Copies current screenshots and visual difference images
    into a directory identified by the scan's unique ID.

    Approved baseline screenshots remain unchanged.

    Args:
        scan_id (str): Unique identifier of the completed scan.

    Returns:
        Path: Directory containing the archived screenshots.

    Raises:
        FileNotFoundError: If an expected screenshot is missing.
    """

    # Create a separate archive directory for this scan.
    scan_directory = HISTORY_DIR / scan_id

    # Define the screenshot categories to preserve.
    categories = {
        "current": "{viewport}.png",
        "diffs": "{viewport}-diff.png",
    }

    # Copy each viewport's screenshot into its archive.
    for category, filename_pattern in categories.items():

        source_directory = SCREENSHOT_DIR / category
        destination_directory = scan_directory / category

        destination_directory.mkdir(
            parents=True,
            exist_ok=True,
        )

        for viewport in ("desktop", "tablet", "mobile"):

            filename = filename_pattern.format(
                viewport=viewport
            )

            source_file = source_directory / filename
            destination_file = destination_directory / filename

            # Do not silently archive an incomplete scan.
            if not source_file.is_file():
                raise FileNotFoundError(
                    f"Missing screenshot: {source_file}"
                )

            # Preserve the image and its file metadata.
            shutil.copy2(
                source_file,
                destination_file,
            )

    logger.info(
        "Archived screenshots for scan %s",
        scan_id,
    )

    return scan_directory

# ---------------------------------------------------------
# Screenshot Capture and Comparison
# ---------------------------------------------------------

def execute_scan(scan_id: str | None = None):
    """
    Execute a visual regression scan and optionally archive images.

    Captures current screenshots, compares them against approved
    baselines, and generates a detailed comparison report.

    When a scan ID is supplied, the resulting screenshots are
    preserved in a scan-specific history directory.

    Args:
        scan_id (str | None): Unique identifier for a background scan.

    Returns:
        dict: Complete visual comparison report.
    """

    # Capture screenshots without modifying approved baselines.
    capture_screenshots("current")

    # Generate the detailed comparison report.
    report = generate_report(detailed=True)

    # Archive screenshots when running a tracked scan.
    if scan_id is not None:
        archive_scan_screenshots(scan_id)

    return report

# ---------------------------------------------------------
# Background Scan Processing
# ---------------------------------------------------------

def process_scan(scan_id: str):
    """
    Execute a scan in the background and persist its progress.

    Scan states:
        pending   - Waiting to begin.
        running   - Screenshot capture is underway.
        completed - Capture and comparison finished.
        failed    - An error prevented completion.

    Args:
        scan_id (str): Unique identifier of the scan.
    """

    # Prevent concurrent scans from modifying shared
    # screenshot and report files.
    if not scan_lock.acquire(blocking=False):

        with jobs_lock:
            job = scan_jobs[scan_id]

            job["state"] = "failed"
            job["error"] = "Another scan is already running."
            job["finished_at"] = datetime.now(
                timezone.utc
            ).isoformat()

            # Persist the failed state.
            save_scan(dict(job))

        return

    try:
        # Mark the scan as running.
        with jobs_lock:
            job = scan_jobs[scan_id]

            job["state"] = "running"

            save_scan(dict(job))

        # Perform screenshot capture and comparison.
        result = execute_scan(scan_id)

        # Save the completed scan and its result.
        with jobs_lock:
            job = scan_jobs[scan_id]

            job["state"] = "completed"
            job["result"] = result
            job["error"] = None
            job["finished_at"] = datetime.now(
                timezone.utc
            ).isoformat()

            save_scan(dict(job))

    except Exception:
        # Record failures without exposing internal
        # exception details to API consumers.
        with jobs_lock:
            job = scan_jobs[scan_id]

            job["state"] = "failed"
            job["error"] = (
                "Screenshot capture or comparison failed."
            )
            job["finished_at"] = datetime.now(
                timezone.utc
            ).isoformat()

            save_scan(dict(job))

        # Preserve the full traceback in server logs.
        logger.exception(
            "Scan job failed: %s",
            scan_id,
        )

    finally:
        # Always release the lock so future scans can run.
        scan_lock.release()


